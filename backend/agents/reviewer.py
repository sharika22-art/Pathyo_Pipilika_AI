import os
import json
import re
from pydantic import BaseModel, Field
from openai import OpenAI

class QuizOption(BaseModel):
    text: str = Field(description="The option text.")
    is_correct: bool = Field(description="True if correct, False otherwise.")

class VerifiedQuestion(BaseModel):
    question: str = Field(description="The revised/verified question text.")
    options: list[QuizOption] = Field(description="Exactly 4 options with exactly one correct option.")
    explanation: str = Field(description="Clear explanation supporting the correct answer.")

class VerifiedQuizResult(BaseModel):
    questions: list[VerifiedQuestion] = Field(description="List of verified, corrected questions.")

def call_openrouter_safely(client, model, messages, response_format=None, temperature=0.2, initial_max_tokens=6000):
    """Automatically catches OpenRouter 402 credit limit errors and retries with adjusted tokens."""
    current_max_tokens = initial_max_tokens
    for _ in range(3):
        try:
            kwargs = {
                "model": model,
                "messages": messages,
                "messages": messages,
                "temperature": temperature,
                "max_tokens": current_max_tokens
            }
            if response_format:
                kwargs["response_format"] = response_format
            return client.chat.completions.create(**kwargs)
        except Exception as e:
            err_str = str(e)
            if "402" in err_str or "can only afford" in err_str:
                match = re.search(r"can only afford\s+(\d+)", err_str)
                if match:
                    affordable_tokens = int(match.group(1))
                    current_max_tokens = max(256, affordable_tokens - 100)
                    print(f"⚡ [Reviewer Dynamic Token Adjuster] Auto-adjusting max_tokens to {current_max_tokens} and retrying...")
                    continue
            raise e
    raise Exception("Failed to complete LLM call after multiple token adjustments.")

def review_and_verify_quiz(
    raw_quiz_json: str, 
    reference_context: str,
    grade: str, 
    subject: str, 
    chapter: str, 
    difficulty: str
) -> str:
    """
    Agent 2: Audits, fact-checks, and polishes the quiz generated by Agent 1 using OpenRouter, 
    verifying against both textbooks and guidebook standards.
    """
    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=os.environ.get("OPENAI_API_KEY") or os.environ.get("OPENROUTER_API_KEY"),
    )

    prompt = f"""
    You are an expert curriculum auditor, senior examiner, and fact-checker for the Bangladesh National Curriculum (NCTB) and top guidebooks.
    
    Review this draft quiz for Grade {grade}, Subject: {subject}, Chapter: {chapter}.
    Target Difficulty: {difficulty}
    
    ---
    REFERENCE CONTEXT (Textbook Theory & Guidebook Standards):
    {reference_context}
    ---
    
    Draft Quiz Content to Audit:
    {raw_quiz_json}

    Audit Tasks & Strict Guidelines:
    1. FACT & CURRICULUM CHECK: Cross-check every question and answer against the Reference Context. Fix any factual inaccuracies.
    2. QUESTION TYPE COVERAGE: Verify that across the questions, the quiz captures a diverse, comprehensive representation of question types found in this chapter (balancing conceptual depth and problem-solving where applicable).
    3. OPTION INTEGRITY: Ensure that for EVERY question, there are exactly 4 options, with **exactly one option** having `is_correct: true` and the remaining 3 having `is_correct: false`.
    4. DIFFICULTY CALIBRATION: Ensure questions accurately match the '{difficulty}' level. If difficulty is **Hard**, verify that the incorrect options (distractors) are highly confusing, close to each other, and designed to trap common student mistakes.
    5. QUALITY CONTROL: Remove any duplicate, repetitive, or poorly framed questions and refine them into board-standard format.
    6. Return the final verified and polished questions strictly in the requested JSON schema.
    """

    try:
        response = call_openrouter_safely(
            client=client,
            model="google/gemini-3.8-flash",
            messages=[
                {
                    "role": "system",
                    "content": "You are a helpful API that outputs strict JSON conforming to this schema: " + json.dumps(VerifiedQuizResult.model_json_schema())
                },
                {"role": "user", "content": prompt}
            ],
            response_format={"type": "json_object"},
            temperature=0.2,
            initial_max_tokens=6000
        )
        return response.choices[0].message.content
    except Exception as e:
        print(f"Error reviewing quiz against context via OpenRouter: {e}")
        return raw_quiz_json