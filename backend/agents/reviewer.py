import os
import json
from pydantic import BaseModel, Field
from google import genai
from google.genai import types

# 1. Initialize client using environment API key explicitly
client = genai.Client(api_key=os.environ.get("GEMINI_API_KEY"))

# 2. Match the exact schema defined in generator.py
class QuizOption(BaseModel):
    text: str = Field(description="The option text.")
    is_correct: bool = Field(description="True if correct, False otherwise.")

class VerifiedQuestion(BaseModel):
    question: str = Field(description="The revised/verified question text.")
    options: list[QuizOption] = Field(description="Exactly 4 options with exactly one correct option.")
    explanation: str = Field(description="Clear explanation supporting the correct answer.")

class VerifiedQuizResult(BaseModel):
    questions: list[VerifiedQuestion] = Field(description="List of verified, corrected questions.")

def review_and_verify_quiz(
    raw_quiz_json: str, 
    textbook_context: str,
    grade: str, 
    subject: str, 
    chapter: str, 
    difficulty: str
) -> str:
    """
    Agent 2: Audits and corrects the quiz generated by Agent 1 
    by cross-checking it directly against the retrieved NCTB textbook chunks.
    """

    prompt = f"""
    You are an expert curriculum auditor and fact-checker for the Bangladesh National Curriculum.
    
    Review this draft quiz for Grade {grade}, Subject: {subject}, Chapter: {chapter}.
    Target Difficulty: {difficulty}
    
    ---
    REFERENCE TEXTBOOK CONTEXT (Ground Truth Chunks):
    {textbook_context}
    ---
    
    Draft Quiz Content to Audit:
    {raw_quiz_json}

    Tasks:
    1. Cross-check every question and answer directly against the Reference Textbook Context above. If a question relies on facts not supported by or conflicting with the reference chunks, rewrite or correct it.
    2. Ensure that for EVERY question, exactly one option has `is_correct: true` and the other 3 have `is_correct: false`.
    3. Ensure the question difficulty genuinely reflects the requested level ('{difficulty}'):
       - Easy: Direct recall / definitions.
       - Medium: Conceptual understanding / application.
       - Hard: Analytical reasoning / multi-step problem solving.
    4. If any question is ambiguous, poorly formulated, or has multiple/zero correct answers, rewrite it cleanly.
    5. Return the verified and polished questions in the required JSON schema.
    """

    try:
        response = client.models.generate_content(
            model='gemini-1.5-flash',
            contents=prompt,
            config=types.GenerateContentConfig(
                response_mime_type="application/json",
                response_schema=VerifiedQuizResult,
                temperature=0.2  # Low temperature for strict factual accuracy
            ),
        )
        return response.text
    except Exception as e:
        print(f"Error reviewing quiz against context: {e}")
        # Fallback to the raw quiz if review call fails
        return raw_quiz_json

